"""Generate the mGBA tracker script and the bridge's game data from a ROM build.

Run after every `make`, because symbol addresses move between builds:

    python3 gen_tracker.py

Reads (relative to the repository root):
    pokeemerald.map                 symbol addresses
    include/player_profile.h        habit names, profile magic/version
    include/telemetry.h             telemetry buffer layout and event types
    include/battle.h                battle actions
    include/constants/battle.h      battle type flags and outcomes
    include/constants/opponents.h   trainer ids
    include/constants/moves.h       move names    (telemetry)
    include/constants/species.h     species names (telemetry)
    include/constants/items.h       item names    (telemetry)
    charmap.txt, src/fonts.c        text encoding and glyph widths (mailbox)
    data/maps/map_groups.json       map names

Writes:
    tools/llm_tracker/build/tracker.lua      load this in mGBA
    tools/llm_tracker/build/game_data.json   used by the bridge to decode events
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

TRACKER_DIR = Path(__file__).resolve().parent
REPO_ROOT = TRACKER_DIR.parent.parent

REQUIRED_SYMBOLS = [
    "gMain",
    "gBattleTypeFlags",
    "gTrainerBattleParameter",
    "gBattleOutcome",
    "gBattleTurnCounter",
    "gSaveBlock1Ptr",
    "gSaveBlock3Ptr",
]
# Only present when the ROM is built with TELEMETRY_ENABLED TRUE (include/config/telemetry.h)
OPTIONAL_SYMBOLS = ["gTelemetry", "gMailbox"]

MAP_SYMBOL_LINE = re.compile(r"^\s+0x([0-9a-fA-F]+)\s+([A-Za-z_]\w*)\s*$")


def parse_map_symbols(map_text, wanted):
    """Return {symbol: address} for the wanted symbols found in a GNU ld map file."""
    found = {}
    for line in map_text.splitlines():
        match = MAP_SYMBOL_LINE.match(line)
        if match and match.group(2) in wanted and match.group(2) not in found:
            found[match.group(2)] = int(match.group(1), 16)
    return found


def parse_enum(header_text, enum_name):
    """Return the member names of a C enum, in order, skipping the trailing *_COUNT."""
    match = re.search(r"enum\s+" + re.escape(enum_name) + r"\s*\{(.*?)\};", header_text, re.S)
    if not match:
        raise ValueError(f"enum {enum_name} not found")
    body = re.sub(r"//.*", "", match.group(1))
    names = [name.split("=")[0].strip() for name in body.split(",")]
    return [name for name in names if name and not name.endswith("_COUNT")]


def parse_enum_values(header_text, enum_name, prefix=""):
    """Return {value: name} for a C enum, keeping the first name with `prefix` for each value.

    Handles explicit numbers (MOVE_POUND = 1), implicit increments, and aliases of
    earlier members (MOVE_SKETCH = MOVES_COUNT_GEN1). Markers without the prefix
    (MOVES_COUNT_GEN1) keep the numbering going but never name a value. Members
    generated by macros (the TMs in items.h) can't be resolved and stay unnamed.
    """
    match = re.search(r"enum\s+(?:__attribute__\(\(\w+\)\)\s+)?" + re.escape(enum_name) + r"\s*\{(.*?)\};",
                      header_text, re.S)
    if not match:
        raise ValueError(f"enum {enum_name} not found")
    body = re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)
    body = re.sub(r"//.*", "", body)  # without re.S, so it stops at the end of the line
    body = re.sub(r"^\s*#.*$", "", body, flags=re.M)  # preprocessor lines inside the enum
    values, known, next_value = {}, {}, 0
    for entry in body.split(","):
        entry = entry.strip()
        if not entry:
            continue
        name, _, expression = (part.strip() for part in entry.partition("="))
        if not re.fullmatch(r"\w+", name):
            next_value = None  # macro-generated members: numbering unknown until the next explicit value
            continue
        if expression:
            if re.fullmatch(r"(0x[0-9a-fA-F]+|\d+)", expression):
                next_value = int(expression, 0)
            else:
                next_value = known.get(expression)  # alias of an earlier member, else unknown
        if next_value is None:
            continue
        known[name] = next_value
        if name.startswith(prefix):
            values.setdefault(next_value, name)
        next_value += 1
    return values


def parse_define(header_text, name):
    match = re.search(r"#define\s+" + re.escape(name) + r"\s+(\w+)", header_text)
    if not match:
        raise ValueError(f"#define {name} not found")
    return int(match.group(1), 0)


def parse_defines(header_text, prefix):
    """Return {value: name} for simple numeric or shift #defines with the given prefix."""
    result = {}
    pattern = re.compile(r"#define\s+(" + re.escape(prefix) + r"\w+)\s+\(?\s*(?:1\s*<<\s*(\d+)|(0x[0-9a-fA-F]+|\d+))\s*\)?\s*(?://.*)?$")
    for line in header_text.splitlines():
        match = pattern.match(line.strip())
        if not match:
            continue
        value = 1 << int(match.group(2)) if match.group(2) else int(match.group(3), 0)
        result.setdefault(value, match.group(1))
    return result


# The ROM is built with -mabi=apcs-gnu, which rounds every struct up to 4 bytes:
# struct ProfileCounter {u8 hits; u8 chances;} takes 4 bytes, not 2.
STAT_STRIDE = 4


def profile_layout(header_text):
    """Byte layout of struct PlayerBattleProfile, mirroring include/player_profile.h."""
    stats = parse_enum(header_text, "PlayerProfileStat")
    status_kinds = parse_enum(header_text, "PlayerProfileStatusKind")
    focus_targets = parse_enum(header_text, "PlayerProfileFocusTarget")
    ace_slots = parse_define(header_text, "PROFILE_ACE_SLOTS")

    offset = 8  # magic(2) version battlesRecorded battlesSet battlesSwitch lastStyle battlesSinceAceDecay
    stats_offset = offset
    offset += STAT_STRIDE * len(stats)
    status_offset = offset
    offset += len(status_kinds)
    focus_offset = offset
    offset += len(focus_targets)
    offset = (offset + 3) & ~3  # u32 acePersonality is 4-byte aligned
    ace_personality_offset = offset
    offset += 4 * ace_slots
    ace_turns_offset = offset
    offset += ace_slots
    size = (offset + 3) & ~3

    return {
        "magic": parse_define(header_text, "PLAYER_PROFILE_MAGIC"),
        "version": parse_define(header_text, "PLAYER_PROFILE_VERSION"),
        "size": size,
        "stats": stats,
        "stats_offset": stats_offset,
        "stat_stride": STAT_STRIDE,
        "status_kinds": status_kinds,
        "status_offset": status_offset,
        "focus_targets": focus_targets,
        "focus_offset": focus_offset,
        "ace_slots": ace_slots,
        "ace_personality_offset": ace_personality_offset,
        "ace_turns_offset": ace_turns_offset,
    }


def telemetry_layout(header_text):
    """Layout and codes of struct TelemetryBuffer, mirroring include/telemetry.h."""
    return {
        "magic": parse_define(header_text, "TELEMETRY_MAGIC"),
        "capacity": parse_define(header_text, "TELEMETRY_CAPACITY"),
        "events_offset": 8,  # u32 magic, u32 head
        "event_size": 8,     # u8 type, u8 arg, u16 a, u16 b, u16 c
        "event_types": [name.removeprefix("TELEMETRY_") for name in parse_enum(header_text, "TelemetryEventType")],
        "results": [name.removeprefix("TELEMETRY_RESULT_") for name in parse_enum(header_text, "TelemetryMoveResult")],
        "sources": [name.removeprefix("TELEMETRY_SOURCE_") for name in parse_enum(header_text, "TelemetrySource")],
        "crit_flag": parse_define(header_text, "TELEMETRY_RESULT_CRIT"),
    }


DIRECTIVE_ENTRY_SIZE = 12  # struct AiTrainerDirective (a STATIC_ASSERT in src/telemetry.c keeps it so)


def mailbox_layout(header_text):
    """Layout of struct Mailbox, mirroring include/telemetry.h: u32 magic, two texts, the League plan."""
    report_size = parse_define(header_text, "MAILBOX_REPORT_SIZE")
    line_size = parse_define(header_text, "MAILBOX_LINE_SIZE")
    max_trainers = parse_define(header_text, "AI_DIRECTIVE_MAX_TRAINERS")
    return {
        "magic": parse_define(header_text, "MAILBOX_MAGIC"),
        "report_offset": 4,
        "report_size": report_size,
        "line_offset": 4 + report_size,
        "line_size": line_size,
        "directive_offset": 4 + report_size + line_size,
        "directive_size": 8 + DIRECTIVE_ENTRY_SIZE * max_trainers,
        "directive": {
            "magic": parse_define(header_text, "AI_DIRECTIVE_MAGIC"),
            "max_trainers": max_trainers,
            "entry_size": DIRECTIVE_ENTRY_SIZE,
            "keep": parse_define(header_text, "AI_DIRECTIVE_KEEP"),
            "weight_max": parse_define(header_text, "AI_DIRECTIVE_WEIGHT_MAX"),
            "punish": {name.removeprefix("DIRECTIVE_PUNISH_"): value
                       for value, name in parse_defines(header_text, "DIRECTIVE_PUNISH_").items()},
            "focus": [name.removeprefix("DIRECTIVE_FOCUS_") for name in parse_enum(header_text, "DirectiveFocusTarget")],
        },
    }


# Trainers the League plan covers: the Elite Four, the Champion and the post-Champion duo
LEAGUE_TRAINERS = ["TRAINER_SIDNEY", "TRAINER_PHOEBE", "TRAINER_GLACIA", "TRAINER_DRAKE", "TRAINER_WALLACE",
                   "TRAINER_LLOPEZ_DUO", "TRAINER_CANETE_DUO"]


def parse_trainer_blocks(party_text, wanted):
    """The documented teams of the wanted trainers from src/data/trainers.party (Showdown-like format)."""
    trainers, current = {}, None
    for raw in party_text.splitlines():
        line = raw.strip()
        header = re.fullmatch(r"=== (\w+) ===", line)
        if header:
            current = trainers[header.group(1)] = {"trainer": header.group(1), "party": []} if header.group(1) in wanted else None
            continue
        if current is None or not line:
            continue
        if line.startswith("- "):                       # a move of the last mon
            if current["party"]:
                current["party"][-1]["moves"].append(line[2:].strip())
        elif line.endswith(" Nature"):                  # "Serious Nature": a mon attribute without a colon
            continue
        elif ":" in line:                               # "Key: value": trainer or mon attribute
            key, _, value = line.partition(":")
            if current["party"] and key == "Ability":
                current["party"][-1]["ability"] = value.strip()
            elif not current["party"] and key in ("Name", "Battle Type", "AI"):
                current[key.lower().replace(" ", "_")] = value.strip()
        else:                                           # "Species @ Item", "Nickname (Species) @ Item", "Species (F)"
            name, _, item = line.partition(" @ ")
            name = re.sub(r"\s*\((M|F)\)$", "", name.strip())
            nickname = re.fullmatch(r".+\(([^()]+)\)", name)
            current["party"].append({"slot": len(current["party"]), "species": nickname.group(1) if nickname else name,
                                     "item": item.strip() or None, "ability": None, "moves": []})
    return trainers


def league_teams(party_text, trainer_ids):
    """game_data["league"]: each League trainer's id, name, lead count and documented team."""
    blocks = parse_trainer_blocks(party_text, set(LEAGUE_TRAINERS))
    teams = []
    for name in LEAGUE_TRAINERS:
        if name not in blocks:
            continue
        block = blocks[name]
        ai = block.get("ai", "")
        aces = 2 if "Double Ace Pokemon" in ai else 1 if "Ace Pokemon" in ai else 0
        teams.append({
            "trainer": name,
            "id": trainer_ids.get(name),
            "name": block.get("name", name),
            "leads": 2 if block.get("battle_type") == "Doubles" else 1,  # the duo are two single trainers
            "ace_slots": aces,
            "party": block["party"],
        })
    return teams


CHARMAP_LINE = re.compile(r"^'(\\.|[^\\])'\s*=\s*((?:[0-9A-Fa-f]{2}\s*)+)")


def parse_charmap(charmap_text):
    """Return {character: [bytes]} for single characters in charmap.txt (first mapping wins).

    Control codes come through as two-character keys: "\\n", "\\l", "\\p".
    """
    chars = {}
    for line in charmap_text.splitlines():
        match = CHARMAP_LINE.match(line.strip())
        if match:
            char = "'" if match.group(1) == "\\'" else match.group(1)
            chars.setdefault(char, [int(b, 16) for b in match.group(2).split()])
    return chars


def parse_glyph_widths(fonts_c, array="gFontNormalLatinGlyphWidths"):
    """Pixel width of each character code in the message box font, from src/fonts.c."""
    match = re.search(re.escape(array) + r"\[\]\s*=\s*\{(.*?)\};", fonts_c, re.S)
    if not match:
        raise ValueError(f"{array} not found")
    return [int(value) for value in re.findall(r"\d+", match.group(1))]


def map_names(map_groups):
    """Return {"group,num": "MapName"} from data/maps/map_groups.json."""
    names = {}
    for group_index, group in enumerate(map_groups["group_order"]):
        for map_index, name in enumerate(map_groups[group]):
            names[f"{group_index},{map_index}"] = name
    return names


def render_lua(template, symbols, layout, telemetry, mailbox, build_id):
    values = {name: "nil" for name in OPTIONAL_SYMBOLS}
    values.update({name: f"0x{address:08X}" for name, address in symbols.items()})
    values.update({
        "PROFILE_MAGIC": f"0x{layout['magic']:04X}",
        "PROFILE_VERSION": str(layout["version"]),
        "PROFILE_SIZE": str(layout["size"]),
        "TELEMETRY_MAGIC": f"0x{telemetry['magic']:08X}",
        "TELEMETRY_CAPACITY": str(telemetry["capacity"]),
        "MAILBOX_MAGIC": f"0x{mailbox['magic']:08X}",
        "MAILBOX_REPORT_OFFSET": str(mailbox["report_offset"]),
        "MAILBOX_REPORT_SIZE": str(mailbox["report_size"]),
        "MAILBOX_LINE_OFFSET": str(mailbox["line_offset"]),
        "MAILBOX_LINE_SIZE": str(mailbox["line_size"]),
        "MAILBOX_DIRECTIVE_OFFSET": str(mailbox["directive_offset"]),
        "MAILBOX_DIRECTIVE_SIZE": str(mailbox["directive_size"]),
        "BUILD_ID": build_id,
    })
    output = template
    for name, value in values.items():
        output = output.replace("{{" + name + "}}", value)
    leftover = re.findall(r"\{\{(\w+)\}\}", output)
    if leftover:
        raise ValueError(f"unfilled template placeholders: {leftover}")
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", type=Path, default=REPO_ROOT, help="repository root")
    parser.add_argument("--out", type=Path, default=TRACKER_DIR / "build", help="output directory")
    args = parser.parse_args()

    map_text = (args.repo / "pokeemerald.map").read_text(errors="replace")
    symbols = parse_map_symbols(map_text, set(REQUIRED_SYMBOLS + OPTIONAL_SYMBOLS))
    missing = [name for name in REQUIRED_SYMBOLS if name not in symbols]
    if missing:
        raise SystemExit(f"symbols missing from pokeemerald.map: {missing} (build the ROM first)")

    def read(path):
        return (args.repo / path).read_text(encoding="utf-8")

    battle_header = read("include/constants/battle.h")
    layout = profile_layout(read("include/player_profile.h"))
    telemetry_header = read("include/telemetry.h")
    telemetry = telemetry_layout(telemetry_header)
    mailbox = mailbox_layout(telemetry_header)
    build_id = hashlib.sha1(json.dumps(symbols, sort_keys=True).encode()).hexdigest()[:10]

    trainer_ids = parse_defines(read("include/constants/opponents.h"), "TRAINER_")

    def names(path, enum_name, prefix):
        return {str(v): n.removeprefix(prefix) for v, n in parse_enum_values(read(path), enum_name, prefix).items()}

    game_data = {
        "build": build_id,
        "profile": layout,
        "telemetry": telemetry,
        "mailbox": mailbox,
        "charmap": parse_charmap(read("charmap.txt")),
        "glyph_widths": parse_glyph_widths(read("src/fonts.c")),
        "battle_type_flags": {str(v): n for v, n in parse_defines(battle_header, "BATTLE_TYPE_").items() if v & (v - 1) == 0},
        "battle_outcomes": {str(v): n for v, n in parse_defines(battle_header, "B_OUTCOME_").items()},
        "battle_actions": names("include/battle.h", "BattleAction", "B_ACTION_"),
        "trainers": {str(v): n for v, n in trainer_ids.items()},
        "league": league_teams(read("src/data/trainers.party"), {n: v for v, n in trainer_ids.items()}),
        "maps": map_names(json.loads(read("data/maps/map_groups.json"))),
        "moves": names("include/constants/moves.h", "Move", "MOVE_"),
        "species": names("include/constants/species.h", "Species", "SPECIES_"),
        "items": names("include/constants/items.h", "Item", "ITEM_"),
    }

    template = (TRACKER_DIR / "lua/tracker_template.lua").read_text(encoding="utf-8")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "tracker.lua").write_text(render_lua(template, symbols, layout, telemetry, mailbox, build_id), encoding="utf-8")
    (args.out / "game_data.json").write_text(json.dumps(game_data, indent=1), encoding="utf-8")

    state = "on" if "gTelemetry" in symbols else "off (TELEMETRY_ENABLED is FALSE in this build)"
    state += ", mailbox " + ("on" if "gMailbox" in symbols else "off")
    print(f"build {build_id}: {len(symbols)} symbols, {len(layout['stats'])} habits, profile {layout['size']} bytes, "
          f"telemetry {state}")
    print(f"names: {len(game_data['moves'])} moves, {len(game_data['species'])} species, {len(game_data['items'])} items")
    print(f"wrote {args.out / 'tracker.lua'}")
    print(f"wrote {args.out / 'game_data.json'}")


if __name__ == "__main__":
    main()
